
CREATE TABLE T_PB_AUDITORIA (
    ID_AUDITORIA           NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_USUARIO             VARCHAR2(128)  NOT NULL,
    TP_OPERACAO            VARCHAR2(10)   NOT NULL,
    DH_OPERACAO            TIMESTAMP(7)   DEFAULT SYSTIMESTAMP NOT NULL,
    NM_TABELA              VARCHAR2(30)   NOT NULL,
    ID_REGISTRO            NUMBER(19),
    TX_VALORES_ANTERIORES  CLOB,
    TX_VALORES_NOVOS       CLOB,

    CONSTRAINT PK_T_PB_AUDITORIA PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CK_AUDITORIA_OPERACAO CHECK (TP_OPERACAO IN ('INSERT','UPDATE','DELETE')),
    
    -- Linha de auditoria com os dois lados nulos não registra nada, o
    -- resultado silencioso de uma trigger escrita errado.
    CONSTRAINT CK_AUDITORIA_VALORES CHECK (
        (TP_OPERACAO = 'INSERT' AND TX_VALORES_ANTERIORES IS NULL AND TX_VALORES_NOVOS IS NOT NULL)
     OR (TP_OPERACAO = 'UPDATE' AND TX_VALORES_ANTERIORES IS NOT NULL AND TX_VALORES_NOVOS IS NOT NULL)
     OR (TP_OPERACAO = 'DELETE' AND TX_VALORES_ANTERIORES IS NOT NULL AND TX_VALORES_NOVOS IS NULL))
);

-- "o que aconteceu com esta linha, do mais recente para o mais antigo"
CREATE INDEX IX_AUDITORIA_TABELA_REG ON T_PB_AUDITORIA (NM_TABELA, ID_REGISTRO, DH_OPERACAO);

-- "o que mudou ontem", sem passar por tabela
CREATE INDEX IX_AUDITORIA_DATA ON T_PB_AUDITORIA (DH_OPERACAO);
