"""Gera a migration Flyway V9 a partir dos blocos 04, 05 e 06 desta pasta.

O que vai para o professor (docs/banco) e o que o Java instala no banco (V9)
precisam ser o mesmo código. Mudou um bloco aqui? Rode de novo:

    python docs/banco/gerar_migration.py

A V9 só pode ser regerada ENQUANTO não tiver rodado em nenhum banco: depois
disso o Flyway recusa a subida por checksum diferente, e a mudança vira uma V10.
"""
from pathlib import Path

PASTA = Path(__file__).resolve().parent
DESTINO = PASTA.parents[1] / "src/main/resources/db/migration/V9__pacotes_plsql_e_auditoria.sql"

CABECALHO = """\
-- =============================================================================
-- V9 — pacotes PL/SQL, trigger de auditoria e a tabela que ela grava
--
-- GERADO por docs/banco/gerar_migration.py a partir dos blocos 04, 05 e 06 de
-- docs/banco — a entrega da disciplina de banco. Não edite aqui: edite lá e
-- gere de novo, para os dois nunca divergirem.
--
-- O backend usa PKG_PB_JSON.PLANO_JSON em GET /api/exportacao/planos-cuidado,
-- e a trigger PB_AUDITA_CONDICAO audita toda escrita em T_PB_CONDICAO_CLINICA,
-- inclusive as que vêm de POST/PUT/DELETE /api/condicao-clinica.
-- =============================================================================

-- T_PB_AUDITORIA (bloco 02). Dentro de um bloco anônimo para não falhar num
-- schema onde os scripts da disciplina já foram rodados à mão (ORA-00955).
BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE T_PB_AUDITORIA (
            ID_AUDITORIA           NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
            NM_USUARIO             VARCHAR2(128)  NOT NULL,
            TP_OPERACAO            VARCHAR2(10)   NOT NULL,
            DH_OPERACAO            TIMESTAMP(7)   DEFAULT SYSTIMESTAMP NOT NULL,
            NM_TABELA              VARCHAR2(30)   NOT NULL,
            ID_REGISTRO            NUMBER(19),
            TX_VALORES_ANTERIORES  CLOB,
            TX_VALORES_NOVOS       CLOB,
            CONSTRAINT PK_T_PB_AUDITORIA PRIMARY KEY (ID_AUDITORIA),
            CONSTRAINT CK_AUDITORIA_OPERACAO CHECK (TP_OPERACAO IN ('INSERT','UPDATE','DELETE')),
            CONSTRAINT CK_AUDITORIA_VALORES CHECK (
                (TP_OPERACAO = 'INSERT' AND TX_VALORES_ANTERIORES IS NULL AND TX_VALORES_NOVOS IS NOT NULL)
             OR (TP_OPERACAO = 'UPDATE' AND TX_VALORES_ANTERIORES IS NOT NULL AND TX_VALORES_NOVOS IS NOT NULL)
             OR (TP_OPERACAO = 'DELETE' AND TX_VALORES_ANTERIORES IS NOT NULL AND TX_VALORES_NOVOS IS NULL))
        )]';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AUDITORIA_TABELA_REG ON T_PB_AUDITORIA (NM_TABELA, ID_REGISTRO, DH_OPERACAO)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AUDITORIA_DATA ON T_PB_AUDITORIA (DH_OPERACAO)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE <> -955 THEN
            RAISE;
        END IF;
END;
/

"""


def main() -> None:
    partes = [CABECALHO]
    for nome in ("04_tipos.sql", "05_pacotes.sql", "06_trigger.sql"):
        texto = (PASTA / nome).read_text(encoding="utf-8").replace("\r\n", "\n").strip()
        partes.append(f"-- >>> docs/banco/{nome}\n\n{texto}\n\n")
    DESTINO.write_text("".join(partes).rstrip() + "\n", encoding="utf-8", newline="\n")
    print(f"gerado: {DESTINO}")


if __name__ == "__main__":
    main()
