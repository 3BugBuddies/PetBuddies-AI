BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables
         WHERE table_name IN (
            'T_PB_CONDICAO_OBSERVADA','T_PB_CHECKIN',
            'T_PB_ITEM_PLANO_CUIDADO','T_PB_PLANO_CUIDADO','T_PB_REGRA_PROTOCOLO',
            'T_PB_PROTOCOLO','T_PB_USUARIO',
            'T_PB_REGRA_PRESCRICAO','T_PB_CONDICAO_CLINICA','T_PB_PRESCRICAO',
            'T_PB_PROCEDIMENTO','T_PB_REGISTRO_ATENDIMENTO','T_PB_JANELA_ATENDIMENTO',
            'T_PB_CONSULTA','T_PB_ANIMAL','T_PB_RESPONSAVEL','T_PB_VETERINARIO',
            'T_PB_CLINICA','T_PB_AUDITORIA', 'T_PB_REGRA_PONTUACAO', 'T_PB_OFERTA')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;

    FOR s IN (
        SELECT sequence_name FROM user_sequences
         WHERE sequence_name LIKE 'SEQ_T_PB_%'
    ) LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
    END LOOP;

    FOR t IN (
        SELECT type_name FROM user_types
         WHERE type_name IN ('PB_PARES_JSON','PB_PAR_JSON','PB_RESULTADO_DOSE')
         ORDER BY CASE type_name WHEN 'PB_PARES_JSON' THEN 1 ELSE 2 END
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TYPE ' || t.type_name || ' FORCE';
    END LOOP;
END;
