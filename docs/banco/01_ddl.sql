    CONSTRAINT CK_ITEM_TIPO CHECK (TP_TIPO_CUIDADO IN
        ('VACINACAO','VERMIFUGACAO','EXAME','RETORNO','CIRURGIA','MEDICACAO','HIGIENE')),
    CONSTRAINT CK_ITEM_STATUS CHECK (ST_STATUS_ITEM IN
        ('PENDENTE','REALIZADO','CANCELADO','ATRASADO')),
 
    CONSTRAINT CK_ITEM_ORIGEM_COER CHECK (
        (TP_ORIGEM = 'PRESCRICAO' AND ID_PRESCRICAO IS NOT NULL)
     OR (TP_ORIGEM = 'PROTOCOLO'  AND ID_REGRA_PROTOCOLO IS NOT NULL)),
    CONSTRAINT CK_ITEM_DESFECHO CHECK (TP_DESFECHO IN
        ('DOSE_CALCULADA','ACIONAR_CLINICA','SEM_DOSE')),

    CONSTRAINT CK_ITEM_DESFECHO_DOSE CHECK (
        (TP_DESFECHO IS NULL             AND NR_DOSE_APLICADA IS NULL)
     OR (TP_DESFECHO =  'DOSE_CALCULADA' AND NR_DOSE_APLICADA IS NOT NULL)
     OR (TP_DESFECHO <> 'DOSE_CALCULADA' AND NR_DOSE_APLICADA IS NULL))
