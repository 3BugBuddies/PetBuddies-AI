-- =============================================================================
-- V5 — receita-modelo da clínica (ADR s3-10)
--
-- O molde de receita que a veterinária escreve uma vez e reaproveita. A
-- prescrição COPIA o conteúdo e guarda de onde veio em T_PB_PRESCRICAO
-- (ID_MATERIAL_ORIGEM, NR_VERSAO_ORIGEM, que já existem desde o V1). Não há FK
-- da prescrição para cá: editar o molde nunca muda receita assinada.
--
-- A regra do molde NÃO congela a condição (T_PB_REGRA_PRESCRICAO congela). O
-- molde é vivo; o que congela é a cópia que vira prescrição. Por isso a
-- coerência "condição numérica exige operador e limite; sim/não não aceita"
-- depende do TP_DADO da condição, que mora em outra tabela, e é checada no
-- service, não por CHECK.
-- =============================================================================

CREATE TABLE T_PB_RECEITA_MODELO (
    ID_RECEITA_MODELO     NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_TITULO             VARCHAR2(120)  NOT NULL,
    NM_MEDICAMENTO        VARCHAR2(150)  NOT NULL,
    NR_DOSE_MIN           NUMBER(8,3)    NOT NULL,
    NR_DOSE_MAX           NUMBER(8,3)    NOT NULL,
    DS_UNIDADE            VARCHAR2(20)   NOT NULL,
    NR_FREQUENCIA_DIA     NUMBER(2)      NOT NULL,
    NR_DURACAO_DIAS       NUMBER(4)      NOT NULL,
    TX_ORIENTACAO         CLOB,
    NR_VERSAO             NUMBER(4)      DEFAULT 1 NOT NULL,
    AT_ATIVO              NUMBER(1)      DEFAULT 1 NOT NULL,
    ID_CLINICA            NUMBER(19)     NOT NULL,
    ID_VETERINARIO_AUTOR  NUMBER(19)     NOT NULL,
    CA_CREATED_AT         TIMESTAMP(7)   DEFAULT SYSTIMESTAMP NOT NULL,
    AT_UPDATED_AT         TIMESTAMP(7),
    CONSTRAINT PK_T_PB_RECEITA_MODELO PRIMARY KEY (ID_RECEITA_MODELO),
    CONSTRAINT UK_RECEITA_MODELO_TITULO UNIQUE (ID_CLINICA, NM_TITULO),
    CONSTRAINT CK_RECEITA_MODELO_FAIXA CHECK (NR_DOSE_MIN <= NR_DOSE_MAX),
    CONSTRAINT CK_RECEITA_MODELO_FREQ CHECK (NR_FREQUENCIA_DIA > 0),
    CONSTRAINT CK_RECEITA_MODELO_DURACAO CHECK (NR_DURACAO_DIAS > 0),
    CONSTRAINT CK_RECEITA_MODELO_ATIVO CHECK (AT_ATIVO IN (0,1))
);

CREATE TABLE T_PB_REGRA_RECEITA_MODELO (
    ID_REGRA_RECEITA_MODELO  NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_RECEITA_MODELO        NUMBER(19)    NOT NULL,
    ID_CONDICAO_CLINICA      NUMBER(19)    NOT NULL,
    TP_OPERADOR              VARCHAR2(20),
    NR_LIMITE                NUMBER(10,3),
    TP_ACAO_DOSE             VARCHAR2(30)  NOT NULL,
    NR_ORDEM                 NUMBER(3)     NOT NULL,
    CA_CREATED_AT            TIMESTAMP(7)  DEFAULT SYSTIMESTAMP NOT NULL,
    AT_UPDATED_AT            TIMESTAMP(7),
    CONSTRAINT PK_T_PB_REGRA_RECEITA_MODELO PRIMARY KEY (ID_REGRA_RECEITA_MODELO),
    CONSTRAINT CK_REGRA_RM_OPERADOR CHECK (TP_OPERADOR IN
        ('MAIOR_QUE','MAIOR_OU_IGUAL','MENOR_QUE','MENOR_OU_IGUAL','IGUAL')),
    CONSTRAINT CK_REGRA_RM_ACAO CHECK (TP_ACAO_DOSE IN
        ('DOSE_MIN','DOSE_MAX','DOSE_PADRAO','ACIONAR_CLINICA','SUSPENDER')),
    CONSTRAINT CK_REGRA_RM_LIMITE CHECK (
        (TP_OPERADOR IS NULL AND NR_LIMITE IS NULL)
     OR (TP_OPERADOR IS NOT NULL AND NR_LIMITE IS NOT NULL))
);

ALTER TABLE T_PB_RECEITA_MODELO ADD CONSTRAINT FK_RECEITA_MODELO_CLINICA
    FOREIGN KEY (ID_CLINICA) REFERENCES T_PB_CLINICA (ID_CLINICA);
ALTER TABLE T_PB_RECEITA_MODELO ADD CONSTRAINT FK_RECEITA_MODELO_AUTOR
    FOREIGN KEY (ID_VETERINARIO_AUTOR) REFERENCES T_PB_VETERINARIO (ID_VETERINARIO);

ALTER TABLE T_PB_REGRA_RECEITA_MODELO ADD CONSTRAINT FK_REGRA_RM_RECEITA
    FOREIGN KEY (ID_RECEITA_MODELO) REFERENCES T_PB_RECEITA_MODELO (ID_RECEITA_MODELO)
    ON DELETE CASCADE;
ALTER TABLE T_PB_REGRA_RECEITA_MODELO ADD CONSTRAINT FK_REGRA_RM_CONDICAO
    FOREIGN KEY (ID_CONDICAO_CLINICA) REFERENCES T_PB_CONDICAO_CLINICA (ID_CONDICAO_CLINICA);

CREATE INDEX IX_REGRA_RM_RECEITA_ORDEM ON T_PB_REGRA_RECEITA_MODELO (ID_RECEITA_MODELO, NR_ORDEM);
CREATE INDEX IX_REGRA_RM_CONDICAO ON T_PB_REGRA_RECEITA_MODELO (ID_CONDICAO_CLINICA);
