-- =============================================================================
-- V8 — envio da consulta realizada para a pontuação no PetBuddies-API (.NET)
--
-- A linha nasce PENDENTE na mesma transação do fechamento da consulta. O envio
-- acontece depois do commit; se o .NET estiver fora do ar, o reenvio agendado
-- tenta de novo. O .NET não pontua a mesma consulta duas vezes, então reenviar
-- é seguro.
-- =============================================================================

CREATE TABLE T_PB_ENVIO_PONTUACAO (
    ID_ENVIO_PONTUACAO  NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_CONSULTA         NUMBER(19)     NOT NULL,
    ST_STATUS_ENVIO     VARCHAR2(20)   DEFAULT 'PENDENTE' NOT NULL,
    NR_TENTATIVAS       NUMBER(5)      DEFAULT 0 NOT NULL,
    DS_ULTIMO_ERRO      VARCHAR2(500),
    DH_ENVIADO_EM       TIMESTAMP(7),
    CA_CREATED_AT       TIMESTAMP(7)   DEFAULT SYSTIMESTAMP NOT NULL,
    AT_UPDATED_AT       TIMESTAMP(7),
    CONSTRAINT PK_T_PB_ENVIO_PONTUACAO PRIMARY KEY (ID_ENVIO_PONTUACAO),
    CONSTRAINT UK_ENVIO_PONT_CONSULTA UNIQUE (ID_CONSULTA),
    CONSTRAINT CK_ENVIO_PONT_STATUS CHECK (ST_STATUS_ENVIO IN ('PENDENTE','ENVIADO','RECUSADO')),
    CONSTRAINT CK_ENVIO_PONT_TENTATIVAS CHECK (NR_TENTATIVAS >= 0)
);

ALTER TABLE T_PB_ENVIO_PONTUACAO ADD CONSTRAINT FK_ENVIO_PONT_CONSULTA
    FOREIGN KEY (ID_CONSULTA) REFERENCES T_PB_CONSULTA (ID_CONSULTA);

CREATE INDEX IX_ENVIO_PONT_STATUS ON T_PB_ENVIO_PONTUACAO (ST_STATUS_ENVIO);
