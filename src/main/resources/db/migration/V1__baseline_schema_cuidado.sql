-- =============================================================================
-- FOREIGN KEYS INTERNAS AO CUIDADO
-- =============================================================================
ALTER TABLE T_PB_REGRA_PROTOCOLO ADD CONSTRAINT FK_REGPROT_PROTOCOLO
    FOREIGN KEY (ID_PROTOCOLO) REFERENCES T_PB_PROTOCOLO (ID_PROTOCOLO);

ALTER TABLE T_PB_PLANO_CUIDADO ADD CONSTRAINT FK_PLANO_PROTOCOLO
    FOREIGN KEY (ID_PROTOCOLO) REFERENCES T_PB_PROTOCOLO (ID_PROTOCOLO);

ALTER TABLE T_PB_ITEM_PLANO_CUIDADO ADD CONSTRAINT FK_ITEM_PLANO
    FOREIGN KEY (ID_PLANO_CUIDADO) REFERENCES T_PB_PLANO_CUIDADO (ID_PLANO_CUIDADO) ON DELETE CASCADE;
-- CICLO DELIBERADO, e por isso as duas colunas são nuláveis: o check-in aponta
-- para o item de que fala (relato por item), e o item aponta para o check-in que
-- o baixou. São relações diferentes entre as mesmas tabelas. O Oracle aceita,
-- porque nenhuma ponta é obrigatória — mas a CARGA precisa de ORDEM: primeiro
-- os relatos gerais, depois os itens, e só então o relato por item. Ver o
-- bloco 03.
ALTER TABLE T_PB_ITEM_PLANO_CUIDADO ADD CONSTRAINT FK_ITEM_CHECKIN
    FOREIGN KEY (ID_CHECKIN) REFERENCES T_PB_CHECKIN (ID_CHECKIN);
ALTER TABLE T_PB_CHECKIN ADD CONSTRAINT FK_CHECKIN_ITEM
    FOREIGN KEY (ID_ITEM_PLANO_CUIDADO) REFERENCES T_PB_ITEM_PLANO_CUIDADO (ID_ITEM_PLANO_CUIDADO);

ALTER TABLE T_PB_ITEM_PLANO_CUIDADO ADD CONSTRAINT FK_ITEM_REGPROT
    FOREIGN KEY (ID_REGRA_PROTOCOLO) REFERENCES T_PB_REGRA_PROTOCOLO (ID_REGRA_PROTOCOLO);

