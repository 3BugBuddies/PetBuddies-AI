-- =============================================================================
-- V1 — BASELINE DO CUIDADO (serviço Java)
-- =============================================================================
-- As TREZE tabelas de que este serviço é dono, com chave primária, restrições de
-- domínio, as FKs INTERNAS ao cuidado e os índices.
--
-- REESCRITO NO PR-J8 (ADR s3-24, 09/09) e AMPLIADO NO PR-J11 (ADR s3-25),
-- e não acrescentado num V4. Legítimo por um motivo só: este baseline NUNCA
-- rodou contra o Oracle. Se tiver rodado antes do merge, este arquivo volta ao
-- que era e a mudança vira V4.
--
-- O QUE MUDOU NO PR-J11 (ADR s3-25) — O REGISTRO COMEÇA A MIGRAR PARA CÁ
--   · Este serviço passou a ser a API única do produto: ele absorve as onze
--     tabelas do registro, uma onda por nível de dependência. O nível 0 são as
--     duas raízes, T_PB_CLINICA e T_PB_RESPONSAVEL, e são as que entram aqui.
--     As outras nove chegam em J12–J16, e o baseline vai a dezesseis tabelas.
--   · O V2 DEIXOU DE EXISTIR. Ele guardava as nove FKs que cruzavam serviço, e
--     nenhuma chave cruza mais nada: cada serviço tem o banco próprio, um RM
--     por serviço, e o schema deste arquivo é exclusivo do Java. As FKs cujas
--     duas pontas já vivem aqui voltaram para o bloco de FKs internas — é o
--     caso de FK_USUARIO_RESPONSAVEL. As que ainda apontam para tabela não
--     migrada voltam junto com ela, no PR do nível dela.
--   · Some com o V2 a projeção domain/readonly, que lia o registro no schema do
--     .NET e nunca teve consumidor.
--
-- O QUE JÁ TINHA MUDADO NO PR-J8 (ADR s3-24)
--   · T_PB_CHECKIN_RESULTADO deixou de existir. As quatro colunas de decisão
--     (ID_CHECKIN, TP_DESFECHO, NR_DOSE_APLICADA, ID_REGRA_APLICADA) moram dentro
--     de T_PB_ITEM_PLANO_CUIDADO, ao lado de ID_PROCEDIMENTO e DT_EXECUTADO_EM,
--     que já estavam lá: são as duas metades do mesmo padrão de baixa.
--   · Sete tabelas renomeadas e dez colunas de enum sufixadas (s3-24 §7b).
--   · T_PB_PROTOCOLO perdeu porte, sexo, castração e faixa de idade — o matching
--     por perfil do pet era herança do bot. Sobrou ES_ESPECIE.
--   · TP_DATA_BASE (ex-TP_ANCORA) perdeu INSTANCIACAO e ganhou ULTIMA_REALIZACAO.
--   · T_PB_PLANO_CUIDADO ganhou TP_CATEGORIA_PLANO, própria e não herdada do
--     protocolo — é o que permite plano de tratamento sem protocolo.
--
-- AS ENTIDADES JPA DE T_PB_CHECKIN E T_PB_CONDICAO_OBSERVADA NASCEM NO PR-J6.
-- A tabela nasce aqui, e isso não quebra o `validate`: ele só confere o que está
-- mapeado.
--
-- TODA PK É NUMBER(19) NESTE ARQUIVO, inclusive nas tabelas do registro, onde o
-- DDL da disciplina declara NUMBER(10). A assimetria vinha do int do C# contra o
-- Long do Java e morreu com o s3-25, porque o Java passou a ser dono dos dois
-- lados. `validate` NÃO pega essa divergência — o dialeto Oracle compara família
-- de tipo, não precisão —, então ela sobreviveria em silêncio.
--
-- CORRIGIDO NO PR-J12: o J11 declarou T_PB_CLINICA e T_PB_RESPONSAVEL com
-- NUMBER(10). O DDL da disciplina não muda por isso: são bancos diferentes
-- desde o s3-25.
--
-- FONTE: database/src/01_ddl.sql, commit a73a473. Este arquivo é derivado; o DDL
-- da disciplina de banco é o canônico em tudo menos na precisão das PKs.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- T_PB_CLINICA — a clínica. Raiz do registro: nada de veterinário nem de
-- condição clínica existe antes dela (ADR s3-16).
--
-- O CNPJ é a identidade externa da clínica e não repete. A aplicação recusa
-- antes, com 409, para que a violação chegue como conflito de domínio e não
-- como erro de driver — mas a garantia é esta restrição, não o código.
-- -----------------------------------------------------------------------------
CREATE TABLE T_PB_CLINICA (
    ID_CLINICA        NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_NOME_CLINICA   VARCHAR2(150)  NOT NULL,
    NR_CNPJ           VARCHAR2(14)   NOT NULL,
    TL_TELEFONE       VARCHAR2(20)   NOT NULL,
    EM_EMAIL          VARCHAR2(254),
    CA_CREATED_AT     TIMESTAMP(7)   DEFAULT SYSTIMESTAMP NOT NULL,
    AT_UPDATED_AT     TIMESTAMP(7),
    CONSTRAINT PK_T_PB_CLINICA PRIMARY KEY (ID_CLINICA),
    CONSTRAINT UK_CLINICA_CNPJ UNIQUE (NR_CNPJ)
);

-- -----------------------------------------------------------------------------
-- T_PB_RESPONSAVEL — o tutor. Sem CPF, sem nascimento e sem endereço: o cadastro
-- do app não pede (decisão I).
--
-- NENHUMA COLUNA É ÚNICA AQUI, e é de propósito. TL_TELEFONE é obrigatório mas
-- repete — dois tutores da mesma casa dividem o número —, e EM_EMAIL é nulável,
-- porque o cadastro nasce no balcão da clínica. Quem procurar unicidade neste
-- cadastro não vai achar: a identidade do tutor é a linha, não o contato.
-- -----------------------------------------------------------------------------
CREATE TABLE T_PB_RESPONSAVEL (
    ID_RESPONSAVEL        NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_NOME_RESPONSAVEL   VARCHAR2(150)  NOT NULL,
    TL_TELEFONE           VARCHAR2(20)   NOT NULL,
    EM_EMAIL              VARCHAR2(254),
    CA_CREATED_AT         TIMESTAMP(7)   DEFAULT SYSTIMESTAMP NOT NULL,
    AT_UPDATED_AT         TIMESTAMP(7),
    CONSTRAINT PK_T_PB_RESPONSAVEL PRIMARY KEY (ID_RESPONSAVEL)
);

