CREATE INDEX IX_CHECKIN_ANIMAL_DATA ON T_PB_CHECKIN (ID_ANIMAL, DH_REGISTRADO_EM);
CREATE INDEX IX_ITEM_PLANO_DATA ON T_PB_ITEM_PLANO_CUIDADO (ID_PLANO_CUIDADO, DT_DATA_ALVO);
CREATE INDEX IX_ITEM_PRESCRICAO ON T_PB_ITEM_PLANO_CUIDADO (ID_PRESCRICAO);
CREATE INDEX IX_ITEM_DESFECHO ON T_PB_ITEM_PLANO_CUIDADO (TP_DESFECHO);

-- A TRAVA DA ADESÃO, herdada de UK_RESULTADO_PRESC_DATA quando a execução virou
-- coluna do item. Índice FUNCIONAL, e não UNIQUE composta, de propósito: no
-- Oracle uma chave PARCIALMENTE nula conta para a unicidade, e todo item de
-- origem PROTOCOLO tem ID_PRESCRICAO nulo — duas vacinas na mesma data
-- colidiriam. Com o CASE, chave inteiramente nula repete à vontade.
CREATE UNIQUE INDEX UX_ITEM_PRESC_DATA ON T_PB_ITEM_PLANO_CUIDADO
    (ID_PRESCRICAO, CASE WHEN ID_PRESCRICAO IS NOT NULL THEN DT_DATA_ALVO END);
