-- A tabela nasce aqui, e isso não quebra o `validate`: ele só confere o que está
-- mapeado.
--
-- POR QUE NÃO HÁ NENHUMA FOREIGN KEY PARA TABELA DO .NET (ADR s3-23)
--   Nove chaves saem daqui e apontam para as onze tabelas do registro, que quem
--   cria é a migration do Entity Framework, no MESMO schema Oracle. Se elas
--   estivessem neste arquivo, este baseline passaria a exigir que o .NET tivesse
--   migrado antes — a ordem de subida viraria dependência dura e o deploy de uma
--   aplicação só quebraria. Elas vivem no V2.
--
