-- domínio, as FKs INTERNAS ao cuidado e os índices.
--
-- REESCRITO NO PR-J8 (ADR s3-24, 09/09), e não acrescentado num V4. Legítimo por
-- um motivo só: este baseline NUNCA rodou contra o Oracle. Se tiver rodado antes
