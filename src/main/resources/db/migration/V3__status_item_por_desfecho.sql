-- O check-in encerra o item de prescricao com o status do desfecho (SUSPENSO e ENCAMINHADO sao novos).
ALTER TABLE T_PB_ITEM_PLANO_CUIDADO DROP CONSTRAINT CK_ITEM_STATUS;

ALTER TABLE T_PB_ITEM_PLANO_CUIDADO ADD CONSTRAINT CK_ITEM_STATUS CHECK (ST_STATUS_ITEM IN
    ('PENDENTE','REALIZADO','SUSPENSO','ENCAMINHADO','CANCELADO','ATRASADO'));

ALTER TABLE T_PB_ITEM_PLANO_CUIDADO ADD CONSTRAINT CK_ITEM_STATUS_DESFECHO CHECK (
    (ST_STATUS_ITEM <> 'SUSPENSO'    OR TP_DESFECHO = 'SEM_DOSE')
AND (ST_STATUS_ITEM <> 'ENCAMINHADO' OR TP_DESFECHO = 'ACIONAR_CLINICA'));
